package BitwisweOperator;

public class someOperations {
    static void main(String[] args) {

        System.out.println(5 & 6);
        System.out.println(5 | 6);
        System.out.println(5^6);
        System.out.println(~5);
        System.out.println(5 << 2); // 5*2pow2
        System.out.println(8 >> 2); // 5/2pow2

    }
}
